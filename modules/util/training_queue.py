"""Generate ordinary training configs and a sequential shell script."""

import copy
import csv
import itertools
import json
import math
import os
import platform
import re
import shlex
import sys
import tempfile
from decimal import Decimal, InvalidOperation
from enum import Enum
from pathlib import Path

from modules.util.path_util import write_json_atomic

REPO_ROOT = Path(__file__).resolve().parents[2]
MARKER = "Generated by OneTrainer training queue"


def parse_values(text):
    text = text.strip()
    if not text:
        raise ValueError("Supply at least one parameter value.")
    if text.startswith("["):
        values = json.loads(text)
        if not isinstance(values, list) or not values:
            raise ValueError("Values must be a nonempty JSON list.")
        return values
    if re.fullmatch(r"[\s\d.eE+:\-]+", text) and text.count(":") == 2:
        try:
            start, end, step = map(Decimal, text.split(":"))
            if not all(x.is_finite() for x in (start, end, step)) or not step or (end - start) * step < 0:
                raise ValueError("Invalid sweep range direction or step.")
            count = int((end - start) / step) + 1
            if count > 100000:
                raise ValueError("Sweep range exceeds 100,000 values.")
            return [
                int(x) if x == x.to_integral_value() else float(x) for x in (start + step * i for i in range(count))
            ]
        except InvalidOperation as exc:
            raise ValueError("Invalid numeric sweep range.") from exc
    values = []
    for part in next(csv.reader([text], skipinitialspace=True)):
        part = part.strip()
        if not part:
            raise ValueError("Empty parameter value.")
        try:
            value = json.loads(part)
        except json.JSONDecodeError:
            value = None if part.lower() in ("none", "null") else part
            if part.lower() in ("true", "false"):
                value = part.lower() == "true"
        values.append(value)
    return values


def load_base(path=None, current=None):
    from modules.util.config.TrainConfig import TrainConfig

    if current is not None:
        config = TrainConfig.default_values().from_dict(current.to_dict())
    else:
        path = Path(path)
        config = TrainConfig.default_values().from_dict(
            json.loads(path.read_text(encoding="utf-8")),
            migrate=not (path.name.startswith("#") and path.name != "#.json"),
        )
    return config.to_pack_dict(secrets=False)


def _set_parameter(config, key, value):
    if not re.fullmatch(r"[A-Za-z_]\w*(?:\[\d+\])*(?:\.[A-Za-z_]\w*(?:\[\d+\])*)*", key):
        raise ValueError(f"Invalid parameter path: {key}")
    tokens = [int(index) if index else name for name, index in re.findall(r"([A-Za-z_]\w*)|\[(\d+)\]", key)]
    if tokens[0] in ("secrets", "workspace_dir", "cache_dir", "debug_dir", "output_model_destination", "continue_last_backup") or key in ("cloud.run_id", "quantization.cache_dir"):
        raise ValueError(f"{key} is managed by the generator.")
    target = config
    try:
        for token in tokens[:-1]:
            target = target[token] if isinstance(target, list | dict) else getattr(target, token)
        leaf = tokens[-1]
        kind = target.types[leaf]
        nullable = target.nullables[leaf]
    except (KeyError, IndexError, AttributeError, TypeError) as exc:
        raise ValueError(f"Unknown scalar parameter: {key}") from exc
    if value is None and nullable:
        pass
    elif isinstance(kind, type) and issubclass(kind, Enum) and isinstance(value, str) and value in kind.__members__:
        value = kind[value]
    elif kind in (int, float) and type(value) in (int, float) and math.isfinite(value):
        if kind is int and value != int(value):
            raise ValueError(f"{key} requires an integer.")
        value = kind(value)
    elif kind not in (str, bool) or type(value) is not kind:
        raise ValueError(f"{key}: incompatible value {value!r}.")
    setattr(target, leaf, value)


def _sweep_configs(settings):
    from modules.util.config.TrainConfig import TrainConfig

    parameters = settings["parameters"]
    keys = [p["key"] for p in parameters]
    total = math.prod(len(p["values"]) for p in parameters)
    if not keys or len(set(keys)) != len(keys) or not 1 <= total <= 100000:
        raise ValueError("Supply unique parameters producing between 1 and 100,000 runs.")
    base = TrainConfig.default_values().from_dict(settings["base_config"])
    for param in parameters:
        for value in param["values"]:
            _set_parameter(base, param["key"], value)
    for values in itertools.product(*(p["values"] for p in parameters)):
        config = copy.deepcopy(base)
        for key, value in zip(keys, values, strict=True):
            _set_parameter(config, key, value)
        yield config


def _launcher(configs, script, power_action):
    windows = script.suffix.lower() == ".bat"

    def quote(value):
        value = str(value)
        if not windows:
            return shlex.quote(value)
        if any(c in value for c in '\r\n"'):
            raise ValueError("Unsupported character in Windows launcher path.")
        return '"' + value.replace("%", "%%") + '"'

    lines = (
        ["@echo off", "rem " + MARKER, "setlocal DisableDelayedExpansion", f"cd /d {quote(REPO_ROOT)} || goto :error"]
        if windows else [
            "#!/usr/bin/env bash", "# " + MARKER, "set -e",
            "trap '",
            "    queue_exit_code=$?",
            '    printf "\\nQueue stopped with exit code %s. See the error above.\\n" "$queue_exit_code" >&2',
            '    if [[ -t 0 ]]; then read -r -p "Press Enter to close..." || :; fi',
            '    exit "$queue_exit_code"',
            "' ERR",
            f"cd -- {quote(REPO_ROOT)}",
        ]
    )
    for path in configs:
        lines.append(f"echo Training config: {quote(path)}" if windows else f"printf '\\nTraining config: %s\\n' {quote(path)}")
        command = [sys.executable, REPO_ROOT / "scripts/train.py", "--config-path", path]
        lines.append(" ".join(map(quote, command)) + (' %*' if windows else ' "$@"'))
        if windows:
            lines.append('if not "%errorlevel%"=="0" goto :error')
    actions = {
        "shutdown": "shutdown /s /t 60" if windows else "shutdown -h now",
        "sleep": (
            'powershell -NoProfile -Command "Add-Type -AssemblyName System.Windows.Forms; '
            "[System.Windows.Forms.Application]::SetSuspendState('Suspend', $false, $false)\""
            if windows else "pmset sleepnow" if platform.system() == "Darwin" else "systemctl suspend"
        ),
    }
    if windows:
        actions["hibernate"] = "shutdown /h"
    if power_action != "none":
        if power_action not in actions:
            raise ValueError("Unsupported completion power action.")
        lines.append(actions[power_action])
        if windows:
            lines.append('if not "%errorlevel%"=="0" goto :error')
    if windows:
        lines.extend([
            "exit /b 0", "", ":error",
            'set "queue_exit_code=%errorlevel%"',
            "echo Queue stopped with exit code %queue_exit_code%. See the error above. 1>&2",
            "pause",
            "exit /b %queue_exit_code%",
        ])
    return "\n".join(lines) + "\n"


def export_queue(settings, script_path, *, overwrite=False):
    script = Path(script_path).resolve()
    if script.suffix.lower() not in (".bat", ".sh"):
        raise ValueError("Choose a .bat or .sh script path.")
    saved_settings = script.with_suffix(".json")
    inputs = [*settings.get("configs", []), settings.get("base_config_path")]
    if any(source and Path(source).resolve() in (script, saved_settings) for source in inputs):
        raise ValueError("Queue output would overwrite an input file.")
    if not overwrite and (script.exists() or saved_settings.exists()):
        raise ValueError("Output already exists. Select 'Overwrite existing' to replace the script and saved queue settings.")
    if settings["mode"] == "Loop":
        configs = [Path(path).resolve() for path in settings["configs"]]
        if not configs or any(not path.is_file() for path in configs):
            raise ValueError("Choose at least one existing training config.")
    elif settings["mode"] == "Sweep":
        # Validate all values before creating an export directory.
        generated = _sweep_configs(settings)
        first = next(generated)
        output = Path(settings["output_dir"]).resolve()
        output.mkdir(parents=True, exist_ok=True)
        directory = Path(tempfile.mkdtemp(prefix="sweep-", dir=output))
        configs = []
        for index, config in enumerate(itertools.chain([first], generated)):
            run = directory / f"run_{index:05d}"
            run.mkdir()
            for key in ("workspace_dir", "cache_dir", "debug_dir"):
                setattr(config, key, str(run / key.removesuffix("_dir")))
            config.quantization.cache_dir = str(run / "quantization")
            config.output_model_destination = str(run / ("model" + config.output_model_format.file_extension()))
            config.continue_last_backup = False
            config.cloud.run_id = f"{directory.name}-{index}"
            path = run / "config.json"
            write_json_atomic(str(path), config.to_pack_dict(secrets=False))
            configs.append(path)
    else:
        raise ValueError("Choose Loop or Sweep.")
    content = _launcher(configs, script, settings["power_action"])
    script.parent.mkdir(parents=True, exist_ok=True)
    write_json_atomic(str(saved_settings), settings)
    script.write_text(content, encoding="utf-8", newline="\n")
    if os.name != "nt":
        script.chmod(script.stat().st_mode | 0o111)
    return saved_settings
